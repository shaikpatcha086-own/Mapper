# =========================================================
# Equivalent Words
# =========================================================

def get_equivalent_words(word):

    word = normalize(word)

    for master, synonyms in BUSINESS_DICTIONARY.items():

        master = normalize(master)

        synonym_list = [normalize(x) for x in synonyms]

        if word == master:
            return [master] + synonym_list

        if word in synonym_list:
            return [master] + synonym_list

    return [word]


# =========================================================
# Expand Tokens
# =========================================================

def expand_tokens(tokens):

    expanded = set()

    for token in tokens:

        for value in get_equivalent_words(token):

            expanded.add(value)

    return sorted(expanded)